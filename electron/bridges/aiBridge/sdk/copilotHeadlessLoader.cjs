"use strict";

/**
 * Headless Copilot CLI launcher for the Copilot SDK's stdio runtime.
 *
 * Problem: on Windows the default resolution (resolveCopilotExecutableForSdk,
 * loader-first) hands @github/copilot's npm-loader.js to the SDK, which spawns
 * `node npm-loader.js` with windowsHide:true (invisible). The loader itself
 * does spawnSync(platformExe, args, {stdio:"inherit"}) WITHOUT windowsHide —
 * spawned from a console-less Electron main process that allocates a NEW
 * console for the CLI, so a console window flashes on every SDK start.
 *
 * Decision (robust variant): the generated wrapper BYPASSES npm-loader.js and
 * spawns the same platform exe the loader would resolve
 * (@github/copilot-<platform>-<arch>, exports "." -> ./copilot.exe) with
 * windowsHide:true. Wrapping the loader instead would not fix the flash: the
 * loader's own spawnSync inherits no console and still allocates one. This
 * does not change which binary runs — the loader only resolves and spawnSyncs
 * that same exe — so the loader-first-vs-native decision from PR #3624 is
 * unaffected at the resolution layer; only the console allocation disappears.
 *
 * Fallback (documented degradation): when the platform exe cannot be
 * resolved, the wrapper spawns the loader via node with windowsHide:true and
 * the console window may still flash.
 *
 * The wrapper is generated (once per distinct content) into os.tmpdir() and
 * its path handed to RuntimeConnection.forStdio({ path }). forStdio only
 * accepts {path, args} — no env surface — so the resolved paths are baked
 * into the wrapper source. The file MUST end in .js: the SDK checks
 * resolvedCliPath.endsWith(".js") to decide whether to spawn `node <path>`,
 * and a .cjs file would be spawned directly (non-executable on Windows).
 * os.tmpdir() has no package.json, so a .js file there defaults to CommonJS.
 */

const { existsSync } = require("fs");
const { createHash } = require("crypto");
const os = require("os");
const path = require("path");
const fs = require("fs");

const WRAPPER_TMP_PREFIX = "netcatty-copilot-headless-";

/**
 * Resolve the platform-native copilot exe the npm-loader would spawn,
 * anchored at the loader's own package root (mirrors the loader's
 * import.meta.resolve origin). Returns null when unresolvable.
 */
function resolveCopilotPlatformExecutable(loaderPath) {
  const normalized = String(loaderPath || "").trim();
  if (!normalized) return null;
  const pkgName = `@github/copilot-${process.platform}-${process.arch}`;
  // Direct-layout candidate: <root>/node_modules/@github/copilot-<p>-<a>/
  // (works even when package.json is absent or exports change).
  const exeName = `copilot${process.platform === "win32" ? ".exe" : ""}`;
  // Resolution roots: the loader's directory (nested node_modules layout,
  // e.g. npm globals) and its grandparent (hoisted layout).
  const roots = [
    path.dirname(normalized),
    path.join(path.dirname(normalized), "..", ".."),
  ];
  for (const root of roots) {
    // Direct candidates: nested (root/node_modules/<pkg>) and hoisted sibling
    // (root/<pkg>) layouts — both work even when package.json is absent.
    for (const direct of [
      path.join(root, "node_modules", pkgName, exeName),
      path.join(root, pkgName, exeName),
    ]) {
      if (existsSync(direct)) return direct;
    }
    try {
      // Pure path resolution — require.resolve never loads the target, so a
      // package whose main is a native exe resolves to the exe path.
      const resolved = require.resolve(pkgName, { paths: [root] });
      if (resolved && existsSync(resolved)) return resolved;
    } catch { /* try next root */ }
  }
  return null;
}

/**
 * Build the wrapper script source with the given paths baked in.
 * @param {object} args
 * @param {string} args.realExePath  path resolveCopilotExecutableForSdk returned
 *                                   (a native exe, or the npm loader .js)
 * @param {string} args.loaderPath   the npm-loader.js path (fallback target)
 */
function buildCopilotHeadlessWrapperSource({ realExePath, loaderPath }) {
  return `"use strict";
/* Generated by Netcatty — headless Copilot CLI wrapper (do not edit).
 * Baked by electron/bridges/aiBridge/sdk/copilotHeadlessLoader.cjs. */
const { spawnSync } = require("child_process");
const { existsSync } = require("fs");
const path = require("path");
const REAL_EXE = ${JSON.stringify(String(realExePath || ""))};
const LOADER_JS = ${JSON.stringify(String(loaderPath || ""))};
const argv = process.argv.slice(2);

/* Replicate npm-loader.js exe resolution: the platform package's exports "."
 * points at the native binary. Anchored at the loader's package root. */
function resolvePlatformExe() {
  if (!LOADER_JS) return null;
  const pkgName = "@github/copilot-" + process.platform + "-" + process.arch;
  const exeName = "copilot" + (process.platform === "win32" ? ".exe" : "");
  const loaderDir = path.dirname(LOADER_JS);
  const roots = [loaderDir, path.join(loaderDir, "..", "..")];
  for (const root of roots) {
    for (const direct of [
      path.join(root, "node_modules", pkgName, exeName),
      path.join(root, pkgName, exeName),
    ]) {
      if (existsSync(direct)) return direct;
    }
    try {
      const resolved = require.resolve(pkgName, { paths: [root] });
      if (resolved && existsSync(resolved)) return resolved;
    } catch (err) { /* try next root */ }
  }
  return null;
}

function run(target, isJsEntry) {
  const result = spawnSync(
    isJsEntry ? process.execPath : target,
    isJsEntry ? [target, ...argv] : argv,
    { stdio: "inherit", windowsHide: true },
  );
  if (result.error) {
    process.stderr.write("netcatty copilot wrapper failed to spawn: " + (result.error.message || String(result.error)) + "\\n");
    process.exit(1);
  }
  process.exit(result.status == null ? 1 : result.status);
}

const isLoaderEntry = /.js$/i.test(REAL_EXE);
if (REAL_EXE && !isLoaderEntry && existsSync(REAL_EXE)) {
  // Baked native exe: spawn it directly, hidden.
  run(REAL_EXE, false);
}
if (isLoaderEntry) {
  // The resolver handed us the npm loader: bypass it by spawning the same
  // platform exe it would resolve, so no visible console is allocated.
  const platformExe = resolvePlatformExe();
  if (platformExe) run(platformExe, false);
}
// Degradation: exe unresolvable — fall back to the loader (its own
// spawnSync lacks windowsHide, so a console window may flash).
if (LOADER_JS && existsSync(LOADER_JS)) {
  run(LOADER_JS, true);
}
process.stderr.write("netcatty copilot wrapper: no copilot executable or loader found\\n");
process.exit(1);
`;
}

/**
 * Generate the headless wrapper for the given resolved CLI path and return
 * the wrapper's temp file path (written once per distinct content). Returns
 * null when nothing was resolved, in which case the caller should pass the
 * original resolution straight through.
 * @param {string | null} resolvedCliPath resolveCopilotExecutableForSdk(...) result
 * @returns {string | null}
 */
function buildCopilotHeadlessWrapperPath(resolvedCliPath) {
  const resolved = String(resolvedCliPath || "").trim();
  if (!resolved) return null;
  const loaderPath = /.js$/i.test(resolved) ? resolved : "";
  const realExePath = loaderPath
    ? (resolveCopilotPlatformExecutable(loaderPath) || loaderPath)
    : resolved;
  const source = buildCopilotHeadlessWrapperSource({ realExePath, loaderPath: loaderPath || resolved });
  const hash = createHash("sha256").update(source).digest("hex").slice(0, 16);
  const wrapperPath = path.join(os.tmpdir(), `${WRAPPER_TMP_PREFIX}${hash}.js`);
  try {
    if (!existsSync(wrapperPath)) {
      fs.writeFileSync(wrapperPath, source, { encoding: "utf8", mode: 0o600 });
    }
  } catch { /* best effort */ }
  return existsSync(wrapperPath) ? wrapperPath : null;
}

module.exports = {
  WRAPPER_TMP_PREFIX,
  buildCopilotHeadlessWrapperSource,
  buildCopilotHeadlessWrapperPath,
  resolveCopilotPlatformExecutable,
};
